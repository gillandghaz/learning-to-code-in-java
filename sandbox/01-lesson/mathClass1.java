public class mathClass1 {
    public static void main(String[] args) {

        System.out.println(Math.PI);
        System.out.println(Math.E);

        double result;

        result = Math.pow(2, 3);  //pangkat
        result = Math.abs(-10);   //absolut/mutlak
        result = Math.sqrt(9);    //akar
        result = Math.round(2.5); //pembulatan
        result = Math.ceil(2.1);  //pembulatas keatas
        result = Math.floor(2.9); //pembulatan kebawah
        result = Math.max(5, 10); //max
        result = Math.min(5, 10); //min

        System.out.println(result);
    }
}
