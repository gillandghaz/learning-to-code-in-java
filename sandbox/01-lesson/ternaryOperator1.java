public class ternaryOperator1 {
    public static void main() {

        // ternary operator ? = Return 1 of 2 if a condition is true
        // variable = (condition) ? ifTrue : ifFalse;
        int score;
        score = 80;

        String hasil = (score >= 80) ? "LULUS" : "GAGAL";
        System.out.println(hasil);
    }
}
